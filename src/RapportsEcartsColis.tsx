import { useMemo, useState } from "react";
import { PageHeader } from "./shared";
import { chargerLogoMoorea } from "./logoMoorea";

// ─── 📦 Rapports d'écart de colis (Récap qualité) ───
// 15/10/2026 — Demande d'Elinathan : « pouvoir avoir des rapports quand il y a un écart de colis
// attendu, avec le logo Moorea, tout propre, en anglais et en français ». Lecture seule : on part des
// arrivages pointés dont le nombre de colis reçus (colisRecus) diffère du nombre attendu (quantite),
// regroupés par livraison (même jour + même fournisseur). Chaque livraison donne un PDF A4 :
// français, anglais, ou bilingue (« Fournisseur / Supplier »), pour l'envoyer au fournisseur.

type Langue = "fr" | "en" | "bi";
type Ligne = { id: string; produit: string; lot: string; lotFournisseur: string; attendu: number; recu: number; ecart: number; unite: string; par: string };
type Livraison = { cle: string; date: string; ts: number; fournisseur: string; lignes: Ligne[] };

const T: Record<string, [string, string]> = {
  titre: ["RAPPORT D'ÉCART DE COLIS", "CASE DISCREPANCY REPORT"],
  fournisseur: ["Fournisseur", "Supplier"],
  livraison: ["Date de livraison", "Delivery date"],
  numero: ["N° de rapport", "Report no."],
  etabli: ["Établi le", "Issued on"],
  par: ["par", "by"],
  produit: ["Produit", "Product"],
  lot: ["Lot Moorea", "Moorea lot"],
  lotF: ["Lot fournisseur", "Supplier lot"],
  attendu: ["Attendus", "Expected"],
  recu: ["Reçus", "Received"],
  ecart: ["Écart", "Difference"],
  total: ["TOTAL", "TOTAL"],
  manque: ["colis manquants", "cases missing"],
  surplus: ["colis en plus", "extra cases"],
  intro: ["Lors de la réception de votre livraison, nous avons constaté les écarts suivants entre les quantités annoncées et les quantités réellement reçues :", "Upon receipt of your delivery, we found the following differences between the quantities announced and the quantities actually received:"],
  commentaire: ["Commentaire", "Comments"],
  demande: ["Merci de bien vouloir établir un avoir ou une régularisation correspondant aux colis manquants.", "Please issue a credit note or adjustment for the missing cases."],
  signature: ["Contrôle réception Moorea", "Moorea receiving inspection"],
  pied: ["Document généré par Moorea — Agréage Rungis", "Document generated by Moorea — Quality control Rungis"],
};
const tr = (cle: string, l: Langue) => (l === "fr" ? T[cle][0] : l === "en" ? T[cle][1] : `${T[cle][0]} / ${T[cle][1]}`);
// Les polices standard du PDF ne savent pas dessiner les émojis ni les espaces fines.
const propre = (s: any) => String(s ?? "").replace(/[   ]/g, " ").replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{200D}]/gu, "").trim();
const num = (v: any): number | null => { const n = typeof v === "number" ? v : parseFloat(String(v ?? "").replace(",", ".")); return isFinite(n) ? n : null; };
const tsDate = (fr: string) => { const m = String(fr || "").match(/^(\d{2})\/(\d{2})\/(\d{4})/); return m ? new Date(+m[3], +m[2] - 1, +m[1], 12).getTime() : 0; };

async function pdfEcart(liv: Livraison, langue: Langue, commentaire: string, auteur: string, imprimer = false) {
  const { default: jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = 210, H = 297, M = 14;
  const vert: [number, number, number] = [48, 90, 85];
  const logo = await chargerLogoMoorea();
  const numero = `EC-${liv.date.split("/").reverse().join("")}-${propre(liv.fournisseur).replace(/[^A-Z0-9]/gi, "").slice(0, 6).toUpperCase()}`;

  // Bandeau Moorea
  doc.setFillColor(...vert); doc.rect(0, 0, W, 34, "F");
  if (logo) doc.addImage(logo, "PNG", M, 7, 20, 20);
  doc.setTextColor(255, 255, 255); doc.setFont("helvetica", "bold"); doc.setFontSize(langue === "bi" ? 13 : 16);
  doc.text(tr("titre", langue), M + 25, 15);
  doc.setFont("helvetica", "normal"); doc.setFontSize(8.5); doc.setTextColor(217, 231, 225);
  doc.text(["MOOREA COMMERCE FRUITS", "69 rue de Perpignan - BP 40376 - 94632 Rungis Cedex - FRANCE", "+33 1 56 70 62 40 - commercial@moorea.fr"], M + 25, 21);

  // Bloc infos
  let y = 44;
  const info = (lib: string, val: string, x: number) => {
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(110, 120, 118); doc.text(lib, x, y);
    doc.setFont("helvetica", "bold"); doc.setFontSize(11); doc.setTextColor(26, 46, 26); doc.text(propre(val), x, y + 5.5);
  };
  info(tr("fournisseur", langue), liv.fournisseur, M);
  info(tr("livraison", langue), liv.date, 120);
  y += 14;
  const etabli = new Date().toLocaleDateString("fr-FR");
  info(tr("numero", langue), numero, M);
  info(tr("etabli", langue), `${etabli}${auteur ? ` ${langue === "en" ? "by" : "par"} ${auteur}` : ""}`, 120);

  // Introduction
  y += 16;
  doc.setFont("helvetica", "normal"); doc.setFontSize(9.5); doc.setTextColor(55, 65, 81);
  const intro = langue === "bi" ? [T.intro[0], T.intro[1]] : [langue === "fr" ? T.intro[0] : T.intro[1]];
  intro.forEach((p, i) => {
    if (i === 1) doc.setFont("helvetica", "italic");
    const l = doc.splitTextToSize(p, W - 2 * M); doc.text(l, M, y); y += l.length * 4.4 + 1.5;
  });

  // Tableau
  y += 3;
  const cols: { cle: string; w: number; droite?: boolean }[] = [
    { cle: "produit", w: 68 }, { cle: "lot", w: 22 }, { cle: "lotF", w: 30 }, { cle: "attendu", w: 20, droite: true }, { cle: "recu", w: 20, droite: true }, { cle: "ecart", w: 22, droite: true },
  ];
  const enTete = () => {
    doc.setFillColor(...vert); doc.rect(M, y, W - 2 * M, langue === "bi" ? 11 : 8, "F");
    doc.setTextColor(255, 255, 255); doc.setFont("helvetica", "bold"); doc.setFontSize(7.5);
    let x = M + 2;
    cols.forEach(c => {
      const lib = langue === "bi" ? [T[c.cle][0], T[c.cle][1]] : [tr(c.cle, langue)];
      doc.text(lib, c.droite ? x + c.w - 4 : x, y + 5, c.droite ? { align: "right" } : undefined);
      x += c.w;
    });
    y += langue === "bi" ? 11 : 8;
  };
  enTete();
  let totA = 0, totR = 0;
  liv.lignes.forEach((l, i) => {
    doc.setFont("helvetica", "normal"); doc.setFontSize(8.5); // même police que le texte écrit (sinon le nom déborde sur le lot)
    const nomL = doc.splitTextToSize(propre(l.produit), cols[0].w - 4);
    const h = Math.max(7, nomL.length * 3.8 + 3);
    if (y + h > H - 60) { doc.addPage(); y = 16; enTete(); }
    if (i % 2) { doc.setFillColor(245, 247, 246); doc.rect(M, y, W - 2 * M, h, "F"); }
    doc.setTextColor(26, 46, 26); doc.setFont("helvetica", "normal"); doc.setFontSize(8.5);
    let x = M + 2;
    const vals = [nomL, l.lot, propre(l.lotFournisseur) || "-", String(l.attendu), String(l.recu)];
    vals.forEach((v, k) => { doc.text(v as any, cols[k].droite ? x + cols[k].w - 4 : x, y + 4.8, cols[k].droite ? { align: "right" } : undefined); x += cols[k].w; });
    doc.setFont("helvetica", "bold");
    if (l.ecart < 0) doc.setTextColor(185, 28, 28); else doc.setTextColor(21, 128, 61);
    doc.text(`${l.ecart > 0 ? "+" : ""}${l.ecart}`, x + cols[5].w - 4, y + 4.8, { align: "right" });
    y += h;
    totA += l.attendu; totR += l.recu;
  });
  // Total
  doc.setDrawColor(...vert); doc.setLineWidth(0.5); doc.line(M, y, W - M, y);
  y += 1;
  doc.setFont("helvetica", "bold"); doc.setFontSize(9.5); doc.setTextColor(26, 46, 26);
  doc.text(tr("total", langue), M + 2, y + 5.5);
  let x = M + 2 + cols[0].w + cols[1].w + cols[2].w;
  const totE = totR - totA;
  doc.text(String(totA), x + cols[3].w - 4, y + 5.5, { align: "right" }); x += cols[3].w;
  doc.text(String(totR), x + cols[4].w - 4, y + 5.5, { align: "right" }); x += cols[4].w;
  if (totE < 0) doc.setTextColor(185, 28, 28); else doc.setTextColor(21, 128, 61);
  doc.text(`${totE > 0 ? "+" : ""}${totE}`, x + cols[5].w - 4, y + 5.5, { align: "right" });
  y += 12;

  // Synthèse
  const manque = liv.lignes.filter(l => l.ecart < 0).reduce((a, l) => a - l.ecart, 0);
  const surplus = liv.lignes.filter(l => l.ecart > 0).reduce((a, l) => a + l.ecart, 0);
  doc.setFontSize(10); doc.setFont("helvetica", "bold");
  if (manque) { doc.setTextColor(185, 28, 28); doc.text(`${manque} ${tr("manque", langue)}`, M, y); y += 5.5; }
  if (surplus) { doc.setTextColor(21, 128, 61); doc.text(`${surplus} ${tr("surplus", langue)}`, M, y); y += 5.5; }

  // Commentaire
  if (commentaire.trim()) {
    y += 3;
    doc.setTextColor(110, 120, 118); doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.text(tr("commentaire", langue), M, y);
    y += 2;
    const l = doc.splitTextToSize(propre(commentaire), W - 2 * M - 6);
    const h = l.length * 4.3 + 5;
    doc.setFillColor(248, 246, 240); doc.roundedRect(M, y, W - 2 * M, h, 2, 2, "F");
    doc.setTextColor(55, 65, 81); doc.setFontSize(9.5); doc.text(l, M + 3, y + 5);
    y += h + 4;
  }
  if (manque) {
    doc.setFont("helvetica", "italic"); doc.setFontSize(9); doc.setTextColor(55, 65, 81);
    (langue === "bi" ? [T.demande[0], T.demande[1]] : [langue === "fr" ? T.demande[0] : T.demande[1]]).forEach(p => { const l = doc.splitTextToSize(p, W - 2 * M); doc.text(l, M, y + 3); y += l.length * 4.3 + 1; });
  }

  // Signature + pied de page
  const ySig = Math.max(y + 14, H - 48);
  doc.setDrawColor(200, 200, 200); doc.setLineWidth(0.3); doc.line(120, ySig + 14, W - M, ySig + 14);
  doc.setFont("helvetica", "normal"); doc.setFontSize(8.5); doc.setTextColor(110, 120, 118);
  doc.text(tr("signature", langue), 120, ySig);
  if (auteur) { doc.setFont("helvetica", "bold"); doc.setTextColor(26, 46, 26); doc.text(propre(auteur), 120, ySig + 6); }
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFillColor(...vert); doc.rect(0, H - 10, W, 10, "F");
    doc.setFont("helvetica", "normal"); doc.setFontSize(7.5); doc.setTextColor(217, 231, 225);
    doc.text(tr("pied", langue), M, H - 4);
    doc.text(`${numero} - ${p}/${pages}`, W - M, H - 4, { align: "right" });
  }
  const suffixe = langue === "fr" ? "FR" : langue === "en" ? "EN" : "FR-EN";
  const nom = `Ecart colis ${propre(liv.fournisseur).replace(/[\\/:*?"<>|]+/g, "-")} ${liv.date.replace(/\//g, "-")} ${suffixe}.pdf`;
  // 16/10/2026 — « 🖨️ Imprimer » : même PDF, envoyé à l'imprimante choisie.
  if (imprimer) { const { imprimerPdf } = await import("./ImpressionPdf"); imprimerPdf({ titre: `Écart de colis — ${liv.fournisseur} (${liv.date})`, nom, base64: doc.output("datauristring").split(",")[1] }); return; }
  doc.save(nom);
}

export function RapportsEcartsColis({ arrivages, onClose, auteur }: { arrivages: any[]; onClose: () => void; auteur?: string }) {
  const [recherche, setRecherche] = useState("");
  const [filtre, setFiltre] = useState<"tous" | "manque" | "surplus">("tous");
  const [ouverte, setOuverte] = useState<string | null>(null);
  const [commentaires, setCommentaires] = useState<Record<string, string>>({});
  const [exclus, setExclus] = useState<Record<string, boolean>>({});
  const [enCours, setEnCours] = useState("");

  const livraisons = useMemo(() => {
    const m = new Map<string, Livraison>();
    (arrivages || []).forEach((a: any) => {
      if (!a || a.test || a.statut === "en attente") return;
      const attendu = num(a.quantite), recu = num(a.colisRecus);
      if (attendu == null || recu == null || attendu === recu) return;
      const date = String(a.date || ""), fournisseur = String(a.fournisseur || "—");
      const cle = `${date}|${fournisseur}`;
      const liv = m.get(cle) || { cle, date, ts: tsDate(date), fournisseur, lignes: [] };
      liv.lignes.push({
        id: a.id, produit: a.produit || "", lot: a.lot_interne ? String(a.lot_interne).padStart(4, "0") : "-", lotFournisseur: a.lot_fournisseur || "",
        attendu, recu, ecart: recu - attendu, unite: a.unite || "colis", par: a.validePar || "",
      });
      m.set(cle, liv);
    });
    return [...m.values()].sort((x, y) => y.ts - x.ts || x.fournisseur.localeCompare(y.fournisseur, "fr"));
  }, [arrivages]);

  const visibles = livraisons.filter(l => {
    if (recherche.trim()) {
      const q = recherche.trim().toLowerCase();
      if (!`${l.fournisseur} ${l.date} ${l.lignes.map(x => `${x.produit} ${x.lot}`).join(" ")}`.toLowerCase().includes(q)) return false;
    }
    if (filtre === "manque") return l.lignes.some(x => x.ecart < 0);
    if (filtre === "surplus") return l.lignes.some(x => x.ecart > 0);
    return true;
  });

  const telecharger = async (liv: Livraison, langue: Langue, imprimer = false) => {
    const lignes = liv.lignes.filter(x => !exclus[x.id]);
    if (!lignes.length) return;
    setEnCours(`${liv.cle}|${imprimer ? "imp" : langue}`);
    try { await pdfEcart({ ...liv, lignes }, langue, commentaires[liv.cle] || "", auteur || "", imprimer); }
    catch (e) { console.error("PDF écart de colis :", e); alert("Le PDF n'a pas pu être créé."); }
    setEnCours("");
  };

  return (
    <div style={{ minHeight: "100vh", background: "#faf9f6" }}>
      <PageHeader titre="📦 Écarts de colis" couleur="#305a55" onBack={onClose} />
      <div style={{ maxWidth: 1000, margin: "0 auto", padding: 16, boxSizing: "border-box" }}>
        <div style={{ background: "#fff", border: "1.5px solid #e8e0d0", borderRadius: 14, padding: 14, marginBottom: 14, display: "flex", gap: 10, flexWrap: "wrap", alignItems: "center" }}>
          <input value={recherche} onChange={e => setRecherche(e.target.value)} placeholder="Fournisseur, produit, date, lot…"
            style={{ flex: "1 1 240px", minWidth: 0, padding: "8px 12px", borderRadius: 9, border: "1.5px solid #e8e0d0", fontSize: 13.5, boxSizing: "border-box" }} />
          {([["tous", "Tous"], ["manque", "Colis manquants"], ["surplus", "Colis en plus"]] as const).map(([v, lib]) => (
            <button key={v} type="button" onClick={() => setFiltre(v)}
              style={{ padding: "7px 13px", borderRadius: 20, border: `1.5px solid ${filtre === v ? "#305a55" : "#e8e0d0"}`, background: filtre === v ? "#eaf2ee" : "#fff", color: filtre === v ? "#305a55" : "#6b7280", fontWeight: 800, fontSize: 12.5, cursor: "pointer" }}>{lib}</button>
          ))}
          <span style={{ fontSize: 11.5, color: "#9ca3af", flexBasis: "100%" }}>
            {visibles.length} livraison{visibles.length > 1 ? "s" : ""} avec un écart entre colis attendus et reçus (arrivages pointés). Un rapport PDF par livraison, en français, en anglais ou bilingue.
          </span>
        </div>

        {!visibles.length ? (
          <p style={{ textAlign: "center", color: "#9ca3af", fontSize: 13, padding: "3rem 0" }}>Aucun écart de colis sur cette sélection.</p>
        ) : (
          <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
            {visibles.map(liv => {
              const ouvert = ouverte === liv.cle;
              const tot = liv.lignes.filter(x => !exclus[x.id]).reduce((a, x) => a + x.ecart, 0);
              return (
                <div key={liv.cle} style={{ background: "#fff", border: `1.5px solid ${ouvert ? "#305a55" : "#eee8dc"}`, borderLeft: `5px solid ${tot < 0 ? "#dc2626" : "#16a34a"}`, borderRadius: 12, overflow: "hidden" }}>
                  <div onClick={() => setOuverte(ouvert ? null : liv.cle)} style={{ display: "flex", alignItems: "center", gap: 10, padding: "11px 14px", cursor: "pointer", flexWrap: "wrap" }}>
                    <div style={{ flex: "1 1 220px", minWidth: 0 }}>
                      <div style={{ fontSize: 14, fontWeight: 800, color: "#1a2e1a", overflowWrap: "anywhere" }}>{liv.fournisseur}</div>
                      <div style={{ fontSize: 11.5, color: "#9ca3af" }}>Livraison du {liv.date} · {liv.lignes.length} produit{liv.lignes.length > 1 ? "s" : ""}</div>
                    </div>
                    <span style={{ fontSize: 13, fontWeight: 900, color: tot < 0 ? "#dc2626" : "#16a34a", background: tot < 0 ? "#fef2f2" : "#f0fdf4", borderRadius: 20, padding: "3px 11px", whiteSpace: "nowrap" }}>{tot > 0 ? "+" : ""}{tot} colis</span>
                    <span onClick={e => e.stopPropagation()} style={{ display: "inline-flex", gap: 6, flexWrap: "wrap" }}>
                      {([["fr", "📄 Français"], ["en", "📄 English"], ["bi", "📄 FR + EN"]] as const).map(([lg, lib]) => (
                        <button key={lg} type="button" onClick={() => telecharger(liv, lg)} disabled={!!enCours}
                          style={{ padding: "6px 11px", borderRadius: 8, border: "1.5px solid #305a55", background: lg === "bi" ? "#305a55" : "#fff", color: lg === "bi" ? "#fff" : "#305a55", fontWeight: 800, fontSize: 12, cursor: "pointer", whiteSpace: "nowrap" }}>
                          {enCours === `${liv.cle}|${lg}` ? "⏳…" : lib}
                        </button>
                      ))}
                      <button type="button" onClick={() => telecharger(liv, "fr", true)} disabled={!!enCours}
                        style={{ padding: "6px 11px", borderRadius: 8, border: "1.5px solid #305a55", background: "#eef4f2", color: "#305a55", fontWeight: 800, fontSize: 12, cursor: "pointer", whiteSpace: "nowrap" }}>
                        {enCours === `${liv.cle}|imp` ? "⏳…" : "🖨️ Imprimer"}
                      </button>
                    </span>
                  </div>
                  {ouvert && (
                    <div style={{ borderTop: "1px solid #f0ebe0", padding: "10px 14px 14px" }}>
                      <div style={{ overflowX: "auto" }}>
                        <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 12.5, minWidth: 520 }}>
                          <thead>
                            <tr style={{ color: "#6b7280", fontSize: 11, textAlign: "left" }}>
                              <th style={{ padding: "4px 6px", width: 28 }}></th><th style={{ padding: "4px 6px" }}>Produit</th><th style={{ padding: "4px 6px" }}>Lot</th>
                              <th style={{ padding: "4px 6px", textAlign: "right" }}>Attendus</th><th style={{ padding: "4px 6px", textAlign: "right" }}>Reçus</th><th style={{ padding: "4px 6px", textAlign: "right" }}>Écart</th>
                            </tr>
                          </thead>
                          <tbody>
                            {liv.lignes.map(l => (
                              <tr key={l.id} style={{ borderTop: "1px solid #f3f4f6", opacity: exclus[l.id] ? 0.4 : 1 }}>
                                <td style={{ padding: "6px" }}><input type="checkbox" checked={!exclus[l.id]} onChange={() => setExclus(x => ({ ...x, [l.id]: !x[l.id] }))} title="Inclure dans le rapport" /></td>
                                <td style={{ padding: "6px", fontWeight: 700, color: "#1f2937" }}>{l.produit}</td>
                                <td style={{ padding: "6px", color: "#6b7280" }}>{l.lot}</td>
                                <td style={{ padding: "6px", textAlign: "right" }}>{l.attendu}</td>
                                <td style={{ padding: "6px", textAlign: "right" }}>{l.recu}</td>
                                <td style={{ padding: "6px", textAlign: "right", fontWeight: 900, color: l.ecart < 0 ? "#dc2626" : "#16a34a" }}>{l.ecart > 0 ? "+" : ""}{l.ecart}</td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                      <label style={{ display: "block", fontSize: 11.5, color: "#6b7280", marginTop: 10 }}>Commentaire ajouté au rapport (facultatif)
                        <textarea value={commentaires[liv.cle] || ""} onChange={e => setCommentaires(c => ({ ...c, [liv.cle]: e.target.value }))} rows={2}
                          placeholder="Ex. : 2 palettes annoncées, 1 seule reçue."
                          style={{ display: "block", width: "100%", marginTop: 4, padding: "8px 10px", borderRadius: 8, border: "1.5px solid #e8e0d0", fontSize: 13, boxSizing: "border-box", resize: "vertical", fontFamily: "inherit" }} />
                      </label>
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
